/** Minimal SQLite dump/load, used for committed schema fixtures (test/fixtures/db/vN.sql). */
import type { Database } from "bun:sqlite";

function literal(v: unknown): string {
  if (v === null || v === undefined) return "NULL";
  if (typeof v === "number" || typeof v === "bigint") return String(v);
  if (v instanceof Uint8Array) return `X'${Buffer.from(v).toString("hex")}'`;
  return `'${String(v).replace(/'/g, "''")}'`;
}

/** Schema objects (tables, indexes, triggers, views), normalized for comparison. */
export function schemaOf(db: Database): { type: string; name: string; sql: string }[] {
  return (
    db
      .query("SELECT type, name, sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY type, name")
      .all() as { type: string; name: string; sql: string }[]
  ).map((o) => ({ ...o, sql: o.sql.replace(/\s+/g, " ").trim() }));
}

export function dumpDb(db: Database): string {
  const version = (db.query("PRAGMA user_version").get() as { user_version: number }).user_version;
  const lines = [`-- tinyrss schema v${version} fixture. Generated by scripts/db-snapshot.ts; do not edit.`, "BEGIN;"];
  const objects = db
    .query("SELECT type, name, sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY rowid")
    .all() as { type: string; name: string; sql: string }[];
  for (const o of objects.filter((o) => o.type === "table")) {
    lines.push(`${o.sql};`);
    for (const row of db.query(`SELECT * FROM "${o.name}"`).values()) {
      lines.push(`INSERT INTO "${o.name}" VALUES (${row.map(literal).join(", ")});`);
    }
  }
  for (const o of objects.filter((o) => o.type !== "table")) lines.push(`${o.sql};`);
  lines.push(`PRAGMA user_version = ${version};`, "COMMIT;", "");
  return lines.join("\n");
}

export function loadDump(db: Database, sql: string) {
  db.exec(sql);
}
